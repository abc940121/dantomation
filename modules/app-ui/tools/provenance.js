#!/usr/bin/env node
'use strict';
// Rebuilds the OpenMausBot table in the root PROVENANCE.md from modules/app-ui/provenance/*.md.
//   node modules/app-ui/tools/provenance.js           rewrite the block between the markers
//   node modules/app-ui/tools/provenance.js --check   exit 1 when the block is stale
// A row is a line that starts with "| modules/app-ui/". Rows are sorted by file path; a path may appear once.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..', '..');
const DIR = path.join(ROOT, 'modules', 'app-ui', 'provenance');
const TARGET = path.join(ROOT, 'PROVENANCE.md');
const START = '<!-- app-ui:omb:start -->';
const END = '<!-- app-ui:omb:end -->';
const HEAD = '| File | Source repo | Path | Commit | Kind |\n|---|---|---|---|---|';

function rows(dir = DIR) {
  const out = new Map();
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.endsWith('.md')).sort() : [];
  for (const f of files) {
    for (const line of fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/)) {
      if (!line.startsWith('| modules/app-ui/')) continue;
      const cells = line.split('|').slice(1, -1).map(c => c.trim());
      if (cells.length !== 5) throw new Error(`provenance/${f}: row needs 5 columns: ${line}`);
      if (out.has(cells[0])) throw new Error(`provenance/${f}: duplicate row for ${cells[0]}`);
      out.set(cells[0], cells);
    }
  }
  return [...out.values()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
}

function block(list) {
  return [START, HEAD, ...list.map(c => '| ' + c.join(' | ') + ' |'), END].join('\n');
}

function render(current, list) {
  const b = block(list);
  const s = current.indexOf(START), e = current.indexOf(END);
  if (s >= 0 && e > s) return current.slice(0, s) + b + current.slice(e + END.length);
  const intro = '\n## OpenMausBot UI files (modules/app-ui)\n\nFiles copied or derived from OpenMausBot (Apache-2.0, see LICENSE-APACHE and NOTICE). Generated by `modules/app-ui/tools/provenance.js` from `modules/app-ui/provenance/*.md`.\n\n';
  const at = current.indexOf('\n## Not used');
  if (at >= 0) return current.slice(0, at) + intro + b + '\n' + current.slice(at);
  return current.replace(/\s*$/, '\n') + intro + b + '\n';
}

if (require.main === module) {
  const list = rows();
  const current = fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n');
  const next = render(current, list);
  if (process.argv.includes('--check')) {
    if (next !== current) { console.error('PROVENANCE.md is stale: run node modules/app-ui/tools/provenance.js'); process.exit(1); }
    console.log(`PROVENANCE.md is current (${list.length} files)`);
  } else {
    if (next !== current) fs.writeFileSync(TARGET, next);
    console.log(`PROVENANCE.md: ${list.length} files`);
  }
}

module.exports = { rows, block, render, START, END };

  const TABLE = { 'en': EN, 'zh-TW': ZH };
  const LANGS = ['en', 'zh-TW'];
  const KEY = 'taskmote.lang';
  const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
  const I = {
    TABLE, LANGS, KEY,
    isLang: l => LANGS.indexOf(l) >= 0,
    // t(lang, key, vars): falls back to English, then to the key itself.
    t(lang, key, vars) {
      const tab = TABLE[lang] || EN;
      let s = has(tab, key) ? tab[key] : (has(EN, key) ? EN[key] : key);
      for (const k of Object.keys(vars || {})) s = s.split('{' + k + '}').join(String(vars[k]));
      return s;
    },
    // Like t, but returns the raw value when the table has no entry (unknown server status words).
    word(lang, prefix, v) {
      const key = prefix + '.' + String(v).replace(/_/g, ' ');
      return has(EN, key) ? I.t(lang, key) : String(v);
    },
    // Question card text for a language: locales[lang] when it fits the options, else the default.
    cardText(q, lang) {
      const l = q && q.locales && q.locales[lang];
      if (l && typeof l.text === 'string' && Array.isArray(l.options) && l.options.length === q.options.length) return { text: l.text, options: l.options };
      return { text: q.text, options: q.options };
    },
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = I; else root.DantoI18n = I;
